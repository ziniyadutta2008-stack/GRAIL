"""Impact-summary drafting. Bedrock is used only when configuration and quota allow it."""

from typing import Protocol

from pydantic import BaseModel, Field

from grail.agents.outputs import GenerationMode
from grail.config import Settings
from grail.inventory.impact import ImpactInput, ImpactSuggestion
from grail.prompts.registry import load_prompt

DRAFT_DISCLAIMER = (
    "Draft only. This is not an approval, a risk acceptance, a certification or an audit opinion."
)


class DraftInvocationError(Exception):
    """The model call failed. Callers keep the deterministic draft."""


class TextInvoker(Protocol):
    def complete(self, *, model_id: str, prompt: str) -> str:
        """Return model text for one prompt."""


class DraftResult(BaseModel):
    text: str
    generation_mode: GenerationMode
    model_id: str | None = None
    prompt_template_id: str
    prompt_template_version: str
    disclaimer: str = DRAFT_DISCLAIMER
    warnings: list[str] = Field(default_factory=list)


def deterministic_impact_draft(impact: ImpactInput, suggestion: ImpactSuggestion) -> str:
    """A reviewable summary that uses only the supplied answers."""
    harms = ", ".join(suggestion.harms_marked_yes) or "none marked yes"
    highs = ", ".join(suggestion.high_risks) or "none"
    missing = ", ".join(suggestion.missing) or "none"
    reasons = " ".join(suggestion.reasons)
    return (
        f"Draft impact summary for {impact.system_name}. "
        "This text was prepared by GRAIL rules and no model was called.\n\n"
        f"Problem: {impact.problem_statement.strip()}\n"
        f"Goals: {impact.goals.strip()}\n"
        f"Registrant assessment: {impact.system_assessment}. "
        f"Registrant proposed tier: {impact.proposed_tier}. "
        f"Suggested tier: {suggestion.suggested_tier}. {reasons}\n"
        f"Harms marked yes: {harms}. High-rated risks: {highs}.\n"
        f"Launch readiness: {suggestion.readiness}. Missing before review: {missing}.\n"
        f"{DRAFT_DISCLAIMER}"
    )


def draft_impact_summary(
    impact: ImpactInput,
    suggestion: ImpactSuggestion,
    settings: Settings,
    *,
    invoker: TextInvoker | None = None,
    invocations_today: int = 0,
) -> DraftResult:
    """Return a Bedrock draft only inside quota. Otherwise return the deterministic draft."""
    prompt = load_prompt("governance_intake")
    fallback = DraftResult(
        text=deterministic_impact_draft(impact, suggestion),
        generation_mode=GenerationMode.DETERMINISTIC_SEED,
        prompt_template_id=prompt.template_id,
        prompt_template_version=prompt.version,
    )
    within_quota = invocations_today < settings.ai_daily_global_limit
    if invoker is None or not settings.ai_assistance_allowed or not within_quota:
        if settings.bedrock_enabled and not settings.ai_assistance_allowed:
            fallback.warnings.append("Bedrock is configured off for this environment or quota.")
        return fallback
    if not settings.bedrock_model_allowlist:
        fallback.warnings.append("No Bedrock model is on the allowlist.")
        return fallback
    model_id = settings.bedrock_model_allowlist[0]
    composed = (
        f"{prompt.text}\n\nDraft a short impact summary from these facts only:\n"
        f"{impact.model_dump_json()}\n{suggestion.model_dump_json()}\n{DRAFT_DISCLAIMER}"
    )
    try:
        text = invoker.complete(model_id=model_id, prompt=composed).strip()
    except DraftInvocationError as exc:
        fallback.warnings.append(
            f"The model call failed ({exc}). The deterministic draft was kept."
        )
        return fallback
    if not text:
        fallback.warnings.append("The model returned no text. The deterministic draft was kept.")
        return fallback
    return DraftResult(
        text=text,
        generation_mode=GenerationMode.BEDROCK,
        model_id=model_id,
        prompt_template_id=prompt.template_id,
        prompt_template_version=prompt.version,
        warnings=["Draft generated by AI. A named person must review it before any decision."],
    )
